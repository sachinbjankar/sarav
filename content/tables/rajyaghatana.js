function fixed(rows, pool, qf, ef) {
  return rows.map(([a, b], i) => {
    const d = pool.filter((x) => x !== b);
    const rot = d.slice(i % d.length).concat(d.slice(0, i % d.length)).slice(0, 3);
    return { s: S, q: qf(a), o: [b, ...rot], e: ef(a, b) };
  });
}

