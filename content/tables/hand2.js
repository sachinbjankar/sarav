export function genHand2() {
  return [
    ...fromTable(P, PCOMM, { from: 'c', to: 'year', q: (x) => `${x.c} कोणत्या वर्षी नेमली गेली?`, e: (x) => `${x.c} (${mr(x.year)}): ${x.work}.`, near: true }),
    ...fromTable(P, PCOMM, { from: 'c', to: 'work', q: (x) => `${x.c} कशाशी संबंधित आहे?`, e: (x) => `${x.c} (${mr(x.year)}): ${x.work}.` }),
    ...fromTable(P, PCOMM, { from: 'work', to: 'c', q: (x) => `‘${x.work}’ — ही शिफारस/कार्य कोणत्या समितीचे?`, e: (x) => `${x.c} (${mr(x.year)}): ${x.work}.` }),
    ...fromTable(P, ART243, { from: 'art', to: 'sub', q: (x) => `राज्यघटनेतील कलम ${x.art} कशाशी संबंधित आहे?`, e: (x) => `कलम ${x.art}: ${x.sub}.` }),
    ...fromTable(P, ART243, { from: 'sub', to: 'art', q: (x) => `‘${x.sub}’ कोणत्या कलमात आहे?`, e: (x) => `${x.sub}: कलम ${x.art}.` }),
    ...fromTable(P, POFF, { from: 'post', to: 'who', q: (x) => `${x.post} कोण असतात?`, e: (x) => `${x.post}: ${x.who}.` }),
    ...fromTable(P, PFACT, { from: 'f', to: 'what', q: (x) => `${x.f} कशाशी संबंधित आहे?`, e: (x) => `${x.f}: ${x.what}.` }),
    ...fromTable(P, PLAW, { from: 'l', to: 'year', q: (x) => `${x.l} — कोणत्या वर्षी?`, e: (x) => `${x.l}: ${mr(x.year)}.`, near: true }),
    ...fromTable(M, MOFF, { from: 'lvl', to: 'who', q: (x) => `${x.lvl} पातळीवरील महसूल प्रशासनाचे प्रमुख अधिकारी कोण?`, e: (x) => `${x.lvl}: ${x.who}.` }),
    ...fromTable(M, MOFF, { from: 'who', to: 'lvl', q: (x) => `${x.who} कोणत्या पातळीवर काम करतात?`, e: (x) => `${x.who}: ${x.lvl} पातळी.` }),
    ...fromTable(M, MFORM, { from: 'f', to: 'what', q: (x) => `${x.f} कशाशी संबंधित आहे?`, e: (x) => `${x.f}: ${x.what}. (७/१२ उतारा = गाव नमुना ७ व १२)`, minPool: 4 }),
    ...fromTable(M, MSYS, { from: 's', to: 'who', q: (x) => `${x.s} कोणी सुरू केली?`, e: (x) => `${x.s}: ${x.who}.`, minPool: 3 }),
    ...fromTable(M, MLAW, { from: 'l', to: 'year', q: (x) => `${x.l} कोणत्या वर्षी अमलात आला?`, e: (x) => `${x.l}: ${mr(x.year)}.`, near: true }),
  ];
}

