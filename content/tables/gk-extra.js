export function genGkExtra() {
  return [
    ...fromTable('itihas', DAYS, { from: 'day', to: 'date', q: (x) => `${x.day} कोणत्या दिवशी साजरा केला जातो?`, e: (x) => `${x.day}: ${x.date}.` }),
    ...fromTable('itihas', DAYS, { from: 'date', to: 'day', q: (x) => `${x.date} हा दिवस कोणता दिन म्हणून साजरा केला जातो?`, e: (x) => `${x.date}: ${x.day}.` }),
    ...fromTable('bhugol', SYMBOL, { from: 'what', to: 'val', q: (x) => `${x.what} कोणता/कोणते?`, e: (x) => `${x.what}: ${x.val}.` }),
    ...fromTable('bhugol', NEWDIST, { from: 'd', to: 'from', q: (x) => `${x.d} जिल्हा कोणत्या जिल्ह्याचे विभाजन करून निर्माण झाला?`, e: (x) => `${mr(x.year)} मध्ये ${x.from} जिल्ह्यातून ${x.d} जिल्हा निर्माण झाला.` }),
    ...fromTable('bhugol', NEWDIST, { from: 'd', to: 'year', near: true, fmt: mr, q: (x) => `${x.d} जिल्ह्याची निर्मिती कोणत्या वर्षी झाली?`, e: (x) => `${x.d}: ${mr(x.year)} (${x.from} जिल्ह्यातून).` }),
    ...fromTable('bhugol', STATEYR, { from: 'st', to: 'year', near: true, fmt: mr, q: (x) => `${x.st} राज्याची निर्मिती कोणत्या वर्षी झाली?`, e: (x) => `${x.st}: ${mr(x.year)}.` }),
    ...fromTable('bhugol', DANCE, { from: 'dance', to: 'st', q: (x) => `‘${x.dance}’ हा नृत्यप्रकार मुख्यतः कोणत्या राज्याशी संबंधित आहे?`, e: (x) => `${x.dance}: ${x.st}.` }),
    ...fromTable('itihas', SAINT, { from: 'saint', to: 'place', q: (x) => `${x.saint} यांच्याशी संबंधित ठिकाण कोणते?`, e: (x) => `${x.saint}: ${x.place}.` }),
  ];
}

