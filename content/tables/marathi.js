function synRows() {
  const rows = [];
  for (const line of SYN.trim().split('\n')) {
    const [head, rest] = line.split('|').map((x) => x.trim());
    const group = [head, ...rest.split(',').map((x) => x.trim())];
    for (const a of group) for (const b of group) if (a !== b) rows.push({ a, b, g: group.join(', ') });
  }
  return rows;
}
function antRows() {
  const rows = [];
  for (const line of ANT.trim().split('\n')) {
    const [a, b] = line.split('|').map((x) => x.trim());
    rows.push({ a, b }, { a: b, b: a });
  }
  return rows;
}

